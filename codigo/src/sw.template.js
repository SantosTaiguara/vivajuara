/* sw.js — Service Worker (topics 10, 48 and 49). Network and cache only: no score, no availability, no sale rule, no business mutation.
   Built by scripts/pwaBuild.js. Modules (§323), all generated or shared, none hand-written per route:
     - request classifier + runtime policy resolver: pwa/swRouting.js, inlined below (the same file the app and the tests run);
     - routing table (RULES): the projection of the cache policy registry (cache/cacheCore.js via scripts/cacheRules.js);
     - precache module: PRECACHE = PrecacheManifest (app shell, offline page, icons, web app manifest) generated by the build;
     - offline pack module: read-only access to packs prepared explicitly by the app (exact version, PUBLIC_SAFE only);
     - update module: install never activates by itself; SKIP_WAITING only after the user accepts (PwaUpdateCoordinator);
     - diagnostics: GET_VERSION answers { serviceWorkerBuildId, cacheSchemaVersion, offlinePackSchemaVersion, apiCompatibilityVersion }.
   Never cached by the worker: other origins (opaque), /api/, auth paths, share routes (/s/<token>), requests with Authorization,
   `no-store` requests or responses, responses with Set-Cookie, non-OK / unexpected content types, any non-GET request.
   Price (commercial.json), version pointers (manifest.json), lots and availability stay NETWORK_ONLY here: the app's data layer keeps
   the last known copy in IndexedDB and labels it ("necessita confirmação"). An API or asset request never receives HTML. */
'use strict';
const VERSION = '__VERSION__';
const META = Object.freeze(Object.assign({ serviceWorkerBuildId: VERSION, cacheSchemaVersion: '1', offlinePackSchemaVersion: '1', apiCompatibilityVersion: '1', queueSchemaVersion: '1' }, (() => { try { return __SW_META__; } catch (e) { return {}; } })()));
const PRECACHE = (() => { try { return __PRECACHE__; } catch (e) { return []; } })(); // [{ url, revision, assetType, bytes?, required, expect? }]
const ASSET_REV = (() => { try { return __ASSET_REV__; } catch (e) { return {}; } })(); // relative path → checksum (sha-256/12 of the published file)
/*__SW_ROUTING__*/
const R = self.WS_ROUTING;
const RULES = (() => { try { return __CACHE_RULES__; } catch (e) { return null; } })() || [
  { id: 'never-api', test: '/api/', strategy: 'BYPASS', klass: 'SENSITIVE_DATA' },
  { id: 'images', test: '\\.(webp|png|jpg|jpeg|svg|woff2?)$', strategy: 'CACHE_FIRST', keep: '/img/', klass: 'STATIC_ASSET', offline: 'PACK', versionRequired: true },
  { id: 'static-json', test: '/(routes|img_list)\\.json$', strategy: 'NETWORK_FIRST', klass: 'VERSIONED_DATA', offline: 'RUNTIME_THEN_PACK' },
  { id: 'data-json', test: '\\.json$', strategy: 'NETWORK_ONLY', klass: 'DYNAMIC_DATA' }
];
const COMPILED = R.compile(RULES);
const SHELL = R.CACHE.shellPrefix + VERSION;            // app shell: one cache per build (appShellVersion ≠ data versions)
const IMG = R.CACHE.imgPrefix + '1';                    // gallery images, one entry per path?v=<checksum> (versioned runtime cache)
const RUNTIME = R.CACHE.runtime;                        // NETWORK_FIRST copies (routes, gallery index)
const NAV_TIMEOUT_MS = 6000, IMG_MAX_ENTRIES = (RULES.find(r => r.id === 'images') || {}).maxEntries || 60;
const scopeUrl = () => self.registration.scope;
const abs = rel => new URL(rel, scopeUrl()).href;
const CTX = { get scopePath() { return new URL(scopeUrl()).pathname; }, rules: COMPILED, precache: new Set(PRECACHE.map(p => p.url.replace(/^\.\//, '')).filter(Boolean)) };
const timeout = (p, ms) => Promise.race([p, new Promise((_, rej) => setTimeout(() => rej(new Error('timeout')), ms))]);
const storable = (r, expect) => R.storable(r, expect); // same-origin OK, no no-store/private, no Set-Cookie, expected content type
const imgKey = (rel, rev) => abs(rel) + '?v=' + rev;
async function notify(msg) { try { for (const c of await self.clients.matchAll({ includeUncontrolled: true })) c.postMessage(msg); } catch (e) { /* no client */ } }

// ------------------------------------------------------------------ precache (install): required entries must succeed, or the install fails and the old worker stays
self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(SHELL);
    await Promise.all(PRECACHE.map(async p => {
      try {
        const r = await fetch(new Request(abs(p.url), { cache: 'reload', credentials: 'same-origin' }));
        if (!storable(r, p.expect)) throw new Error('precache ' + p.url + ' HTTP ' + r.status);
        await c.put(abs(p.url), r);
      } catch (err) { if (p.required) throw err; }
    }));
  })().catch(async err => { await caches.delete(SHELL); await notify({ type: 'SW_EVENT', name: 'sw_install_failure', build: VERSION }); throw err; }));
  // no skipWaiting() here (§38): a waiting version is activated only when the user accepts it
});

// ------------------------------------------------------------------ activate: drop only what this worker owns and no longer uses
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(R.obsoleteCaches(keys, { shell: SHELL, img: IMG }).map(k => caches.delete(k)));
    try { const c = await caches.open(IMG); for (const k of await c.keys()) { const u = new URL(k.url), rel = R.relPath(u.pathname, CTX.scopePath); if (!ASSET_REV[rel] || u.searchParams.get('v') !== ASSET_REV[rel]) await c.delete(k); } } catch (err) { /* nothing to prune */ }
    if (self.registration.navigationPreload) { try { await self.registration.navigationPreload.enable(); } catch (err) { /* optional (§257) */ } }
    await self.clients.claim();
    await notify({ type: 'SW_EVENT', name: 'sw_activate_success', build: VERSION });
  })());
});

// ------------------------------------------------------------------ messages from the page
self.addEventListener('message', e => {
  const t = e.data && e.data.type;
  if (t === 'SKIP_WAITING') self.skipWaiting(); // only sent by the page after the user accepted the update
  else if (t === 'GET_VERSION') { const port = e.ports && e.ports[0]; (port || e.source).postMessage({ type: 'SW_VERSION', ...META }); }
});
// Background Sync (optional, §110): the worker never replays business mutations; it only wakes the app's SyncCoordinator
self.addEventListener('sync', e => { if (e.tag === 'ws-sync') e.waitUntil(notify({ type: 'SYNC_REQUESTED' })); });

// ------------------------------------------------------------------ fetch
self.addEventListener('fetch', e => {
  const req = e.request;
  let d;
  try { d = R.classify({ method: req.method, url: req.url, mode: req.mode, hasAuthorization: req.headers.has('authorization'), cacheMode: req.cache, sameOrigin: new URL(req.url).origin === self.location.origin }, CTX); }
  catch (err) { return; } // never break a request because of the classifier
  if (!d.handle) return; // network, untouched (mutations, auth, API, share sub-resources, no-store, unknown routes)
  e.respondWith(route(e, req, d));
});
async function route(e, req, d) {
  if (d.offline === 'SHELL') return navigateShell(e, req);
  if (d.klass === 'NAVIGATION' || d.klass === 'SHARE') return navigateOther(req, d);
  if (d.strategy === 'PRECACHE') return precached(req);
  if (d.strategy === 'CACHE_FIRST') return cacheFirst(req, d);
  if (d.strategy === 'NETWORK_FIRST') return networkFirst(req, d);
  return networkThenPack(req, d);
}
/** app-shell navigation: network first (navigation preload when available), shell of this build when offline */
async function navigateShell(e, req) {
  try {
    const pre = e.preloadResponse ? await e.preloadResponse.catch(() => null) : null;
    const r = pre || await timeout(fetch(req), NAV_TIMEOUT_MS);
    if (storable(r, 'SHELL')) { const copy = r.clone(); caches.open(SHELL).then(c => c.put(scopeUrl(), copy)).catch(() => {}); }
    return r;
  } catch (err) {
    const c = await caches.open(SHELL); const shell = await c.match(scopeUrl());
    return shell || offlinePage('OFFLINE_PAGE');
  }
}
/** other navigations (non-shell routes, share links): never the app shell; offline → neutral offline page */
async function navigateOther(req, d) {
  try { return await fetch(req); } catch (err) { return offlinePage(d.offline === 'SHARE_OFFLINE_PAGE' ? 'SHARE_OFFLINE_PAGE' : 'OFFLINE_PAGE'); }
}
async function offlinePage(kind) {
  const t = R.OFFLINE_TEXT[kind] || R.OFFLINE_TEXT.OFFLINE_PAGE;
  let html = null;
  try { const c = await caches.open(SHELL); const r = await c.match(abs('offline.html')); if (r) html = await r.text(); } catch (err) { /* none */ }
  if (!html) html = '<!doctype html><meta charset="utf-8"><title>Offline</title><h1>{{TITLE}}</h1><p>{{BODY}}</p>';
  html = html.replace(/\{\{HOME\}\}/g, scopeUrl()).replace(/\{\{TITLE\}\}/g, t.title).replace(/\{\{BODY\}\}/g, t.body);
  return new Response(html, { status: 503, headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' } });
}
async function precached(req) {
  const c = await caches.open(SHELL); const hit = await c.match(req.url, { ignoreSearch: true });
  if (hit) return hit;
  return fetch(req);
}
/** images: gallery kept per exact revision; other images go to the network and fall back to an exact-version offline pack copy */
async function cacheFirst(req, d) {
  const rev = ASSET_REV[d.rel];
  if (d.store === 'IMG' && rev) {
    const c = await caches.open(IMG); const key = imgKey(d.rel, rev); const hit = await c.match(key);
    if (hit) return hit;
    try {
      const r = await fetch(req);
      if (storable(r, 'IMAGE')) { const copy = r.clone(); c.put(key, copy).then(() => trim(c, IMG_MAX_ENTRIES)).catch(() => {}); }
      return r;
    } catch (err) { return (await packFallback(d)) || Response.error(); }
  }
  try { return await fetch(req); } catch (err) { return (await packFallback(d)) || Response.error(); }
}
async function trim(c, max) { const keys = await c.keys(); for (const k of keys.slice(0, Math.max(0, keys.length - max))) await c.delete(k); }
async function networkFirst(req, d) {
  const key = abs(d.rel);
  try {
    const r = await timeout(fetch(req), NAV_TIMEOUT_MS);
    if (storable(r, d.expect)) { const copy = r.clone(); caches.open(RUNTIME).then(c => c.put(key, copy)).catch(() => {}); }
    return r;
  } catch (err) {
    const c = await caches.open(RUNTIME); const hit = await c.match(key);
    return hit || (await packFallback(d)) || Response.error();
  }
}
async function networkThenPack(req, d) {
  try { return await fetch(req); } catch (err) { return (await packFallback(d)) || Response.error(); }
}
/** exact-version copy from an explicitly prepared offline pack; marked so the app can tell it apart from a network answer */
async function packFallback(d) {
  if (!d.offline || !/PACK/.test(d.offline)) return null;
  try {
    const ic = await caches.open(R.CACHE.packIndex); const ir = await ic.match(abs(R.PACK_INDEX_KEY)); if (!ir) return null;
    const entry = R.pickPackEntry(await ir.json(), d.rel, { versionRequired: d.versionRequired, expectedChecksum: ASSET_REV[d.rel] });
    if (!entry) return null;
    const pc = await caches.open(entry.cacheName); const r = await pc.match(abs(entry.key)); if (!r) return null;
    const h = new Headers(r.headers); h.set('x-ws-offline-pack', entry.packId); h.set('x-ws-resource-version', entry.checksum); h.set('cache-control', 'no-store');
    return new Response(r.body, { status: 200, headers: h });
  } catch (err) { return null; }
}
