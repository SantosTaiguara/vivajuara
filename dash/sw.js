async function navigateOther(req, d) {
  try { return await fetch(req); } catch (err) { return offlinePage(d.offline === 'SHARE_OFFLINE_PAGE' ? 'SHARE_OFFLINE_PAGE' : 'OFFLINE_PAGE'); }
}
async function offlinePage(kind) {
  const t = R.OFFLINE_TEXT[kind] || R.OFFLINE_TEXT.OFFLINE_PAGE;
  let html = null;
  try { const c = await caches.open(SHELL); const r = await c.match(abs('offline.html')); if (r) html = await r.text(); } catch (err) { /* none */ }
  if (!html) html = '<!doctype html><meta charset="utf-8"><title>Offline</title><h1>{{TITLE}}</h1><p>{{BODY}}</p>';
  html = html.replace(/\{\{HOME\}\}/g, scopeUrl()).replace(/\{\{TITLE\}\}/g, t.title).replace(/\{\{BODY\}\}/g, t.body);
  return new Response(html, { status: 503, headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' } });
}
async function precached(req) {
  const c = await caches.open(SHELL); const hit = await c.match(req.url, { ignoreSearch: true });
  if (hit) return hit;
  return fetch(req);
}
/** images: gallery kept per exact revision; other images go to the network and fall back to an exact-version offline pack copy */
async function cacheFirst(req, d) {
  const rev = ASSET_REV[d.rel];
  if (d.store === 'IMG' && rev) {
    const c = await caches.open(IMG); const key = imgKey(d.rel, rev); const hit = await c.match(key);
    if (hit) return hit;
    try {
      const r = await fetch(req);
      if (storable(r, 'IMAGE')) { const copy = r.clone(); c.put(key, copy).then(() => trim(c, IMG_MAX_ENTRIES)).catch(() => {}); }
      return r;
    } catch (err) { return (await packFallback(d)) || Response.error(); }
  }
  try { return await fetch(req); } catch (err) { return (await packFallback(d)) || Response.error(); }
}
async function trim(c, max) { const keys = await c.keys(); for (const k of keys.slice(0, Math.max(0, keys.length - max))) await c.delete(k); }
async function networkFirst(req, d) {
  const key = abs(d.rel);
  try {
    const r = await timeout(fetch(req), NAV_TIMEOUT_MS);
    if (storable(r, d.expect)) { const copy = r.clone(); caches.open(RUNTIME).then(c => c.put(key, copy)).catch(() => {}); }
    return r;
  } catch (err) {
    const c = await caches.open(RUNTIME); const hit = await c.match(key);
    return hit || (await packFallback(d)) || Response.error();
  }
}
async function networkThenPack(req, d) {
  try { return await fetch(req); } catch (err) { return (await packFallback(d)) || Response.error(); }
}
/** exact-version copy from an explicitly prepared offline pack; marked so the app can tell it apart from a network answer */
async function packFallback(d) {
  if (!d.offline || !/PACK/.test(d.offline)) return null;
  try {
    const ic = await caches.open(R.CACHE.packIndex); const ir = await ic.match(abs(R.PACK_INDEX_KEY)); if (!ir) return null;
    const entry = R.pickPackEntry(await ir.json(), d.rel, { versionRequired: d.versionRequired, expectedChecksum: ASSET_REV[d.rel] });
    if (!entry) return null;
    const pc = await caches.open(entry.cacheName); const r = await pc.match(abs(entry.key)); if (!r) return null;
    const h = new Headers(r.headers); h.set('x-ws-offline-pack', entry.packId); h.set('x-ws-resource-version', entry.checksum); h.set('cache-control', 'no-store');
    return new Response(r.body, { status: 200, headers: h });
  } catch (err) { return null; }
}
